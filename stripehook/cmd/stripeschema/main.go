// Command stripeschema writes stripehook.Schema, the stripe_event and
// stripe_object tables, to a file for sqlc. Run it with go run (or go tool)
// so the schema comes from the stripehook version in the app's go.mod:
//
//	//go:generate go run github.com/timwmillard/golite/stripehook/cmd/stripeschema sqlc/stripehook.sql
//
// With no argument it writes to standard output.
package main

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/timwmillard/golite/stripehook"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "stripeschema:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	const header = "-- Generated by stripeschema for sqlc. Don't edit or migrate with it: stripehook.Migrate creates these tables.\n\n"
	switch len(args) {
	case 0:
		_, err := fmt.Print(header + stripehook.Schema)
		return err
	case 1:
		if err := os.MkdirAll(filepath.Dir(args[0]), 0o755); err != nil {
			return err
		}
		return os.WriteFile(args[0], []byte(header+stripehook.Schema), 0o644)
	default:
		return fmt.Errorf("usage: stripeschema [file]")
	}
}
